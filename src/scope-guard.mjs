// 질문 종류 관문 (CLAUDE.md 생성 계약): 비목표 질문은 검색·LLM 전에 멈춘다
// 검색 점수는 "무엇에 관한 질문인가"만 보므로, "답할 수 있는 종류인가"는 여기서 문장 패턴으로 거른다.
// 원칙: 단어 하나("성공", "평가", "아이디어")가 아니라 예측·평가 요청·생성 요청 '표현'만 잡는다.
export const SCOPE_RULES = [
  {
    type: "성공 예측",
    patterns: [
      /(성공|흥행|히트)\s*(할|하게\s*될|할\s*수\s*있을)\s*(까|지)/,
      /(성공|흥행)\s*(할\s*)?가능성/,
      /대박\s*(날|나)\s*(까|지)/,
      /잘\s*(될|팔릴|나갈|먹힐|통할)\s*(까|지)/,
      /(뜰|먹힐|통할|팔릴|망할)\s*까/,
      /인기\s*(가\s*)?(있|많|얻|끌)\s*을\s*(까|지)/,
      // 짐작을 묻는 말투: "성공하겠지?", "잘 되겠지?", "팔리겠지?"
      /(성공|흥행|히트)\s*(하겠|할\s*것\s*같)/,
      /잘\s*(되|팔리|나가|먹히|통하)\s*겠/,
      /(뜨|먹히|통하|팔리|망하)겠/,
      /인기\s*(가\s*)?(있|많)\s*겠/,
    ],
  },
  {
    type: "작품 평가",
    patterns: [
      /평가\s*(해\s*)?(줘|주세요|좀)/,
      /피드백\s*(해\s*)?(줘|주세요|좀)/,
      /점수\s*(좀\s*)?(매겨|줘)|몇\s*점/,
      /(내|제|우리|이)\s*(캐릭터|작품|아이디어|기획|그림|설정|스토리|세계관)[^?？]*(어때|괜찮|별로|좋아\s*\?|좋을까)/,
    ],
  },
  {
    type: "아이디어 생성",
    patterns: [
      /아이디어\s*(좀\s*)?(줘|주세요|내\s*줘|추천|만들어|짜\s*줘)/,
      /(캐릭터|이름|스토리|세계관|설정|로그라인|줄거리)\s*(좀\s*)?(만들어|지어|짜|생성해)\s*(줘|주)/,
    ],
  },
];

export const SCOPE_MESSAGE = "작품 평가·아이디어 생성·성공 예측은 자료로 판단할 수 없어 확인 불가";

export function checkScope(question) {
  for (const rule of SCOPE_RULES) {
    for (const p of rule.patterns) {
      const m = question.match(p);
      if (m) return { blocked: true, type: rule.type, matched: m[0] };
    }
  }
  return { blocked: false };
}
