// 질문 종류 관문 검사 (모델 없이 실행): node src/test-scope.mjs
import { checkScope } from "./scope-guard.mjs";

// 막아야 하는 질문
const BLOCK = [
  "내 캐릭터 아이디어가 성공할까?", "이 캐릭터 성공할 수 있을까?", "내 IP 흥행할지 알려줘",
  "이 기획 성공 가능성은?", "이거 대박 날까?", "이 굿즈 잘 팔릴까?", "이 캐릭터 뜰까?",
  "이 이모티콘 인기 있을까?", "내 캐릭터 평가해 줘", "내 시나리오 피드백 좀", "이 그림 몇 점이야?",
  "내 캐릭터 디자인 어때?", "우리 세계관 괜찮아?", "캐릭터 아이디어 좀 줘", "새 IP 아이디어 추천해 줘",
  "캐릭터 이름 지어 줘", "세계관 설정 만들어 줘", "로그라인 짜 줘",
  "이 캐릭터 성공하겠지?", "이거 잘 되겠지?", "굿즈 팔리겠지?", "이 캐릭터 인기 많겠지?", "이 IP 흥행할 것 같아?",
];
// 막으면 안 되는 질문 (자료로 답할 수 있음)
const PASS = [
  "IP가 뭔지 알려줘", "카카오프렌즈가 성공한 과정은?", "엄마 까투리의 로컬 브랜딩 성공 요인은?",
  "캐릭터 IP 성공 사례 알려줘", "망그러진 곰은 왜 인기를 얻었어?", "픽사 브레인트러스트는 작품을 어떻게 평가해?",
  "세이브 더 캣에 대한 평가와 비판은?", "로그라인은 어떻게 만들어?", "세계관을 만들 때 참고할 이론은?",
  "스토리 아이디어를 얻는 방법은?", "영웅의 여정은 어떤 단계야?", "스토리보드는 어떻게 쓰여?", "흥행한 지브리 작품은?", "IP가 뭐야?", "IP에 대해 알려줘",
  "모델 시트는 왜 필요해?", "OSMU가 뭐야?", "최고심 인스타그램 전략은?", "토이 스토리는 언제 나왔어?",
];

let fail = 0;
for (const q of BLOCK) {
  const r = checkScope(q);
  if (!r.blocked) fail++;
  console.log(`${r.blocked ? "✅" : "❌"} 막음  ${q}${r.blocked ? `  (${r.type}: "${r.matched}")` : "  ← 못 막음"}`);
}
for (const q of PASS) {
  const r = checkScope(q);
  if (r.blocked) fail++;
  console.log(`${r.blocked ? "❌" : "✅"} 통과  ${q}${r.blocked ? `  ← 잘못 막음 (${r.type}: "${r.matched}")` : ""}`);
}
console.log(`\n막아야 할 ${BLOCK.length}개, 통과해야 할 ${PASS.length}개 중 실패 ${fail}건`);
process.exitCode = fail ? 1 : 0;
